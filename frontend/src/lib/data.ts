export function getProductBySlug(slug: string) {
  const product = products.find(p => p.slug === slug) ?? null
  if (!product) return { product: null, related: [] }
  const related = products.filter(p => p.id !== product.id && p.category_id === product.category_id).slice(0, 4)
  return { product, related }
}

export function getProductsByCategory(categoryId?: string | null, search?: string | null) {
  let result = [...products]
  if (categoryId) result = result.filter(p => String(p.category_id) === String(categoryId))
  if (search) {
    const q = search.toLowerCase()
    result = result.filter(p =>
      p.name.toLowerCase().includes(q) ||
      p.name_fr.toLowerCase().includes(q) ||
      (p.model_number?.toLowerCase().includes(q) ?? false)
    )
  }
  return { data: result, total: result.length }
}